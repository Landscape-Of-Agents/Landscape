#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub(crate) enum ReviewLevel {
    None,
    Peer,
    Owner,
    Admin,
}

/** How a business reference is known to apply
 * Variants
    - ExplicitlyMapped - mapped to an authoritative source (a spec, a system of record)
    - HumanConfirmed - confirmed by a named person
    - InferredUnverified - inferred (for example by a model); not authoritative
    - Unmapped - no mapping
*/
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub(crate) enum MappingStatus {
    ExplicitlyMapped,
    HumanConfirmed,
    InferredUnverified,
    Unmapped,
}

impl MappingStatus {
    /** Report whether the mapping is authoritative (explicit or human-confirmed)
     * Input
        - None (uses self)
     * Output
        - bool
    */
    pub(crate) fn authoritative(self) -> bool {
        matches!(self, Self::ExplicitlyMapped | Self::HumanConfirmed)
    }
}

