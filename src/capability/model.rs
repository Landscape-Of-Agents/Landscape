/** What a dependency points to
 * Variants
    - LandscapeEntity, Zone, Flow - Landscape (by id and version)
    - Repository - a repository and revision
    - Service, Api, Database, Schema, Infrastructure - system resources
    - Capability - another capability (by id and version constraint)
    - ExternalSystem - an external system or adapter
    - Contract - a Crane/AgentScript contract (registry generation)
    - Policy - a Crane/AgentScript policy (name and version digest)
    - EvidencePack - a Work Capture Evidence Pack
    - Context - other context needed to explain applicability
*/
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub(crate) enum DependencyKind {
    LandscapeEntity,
    Zone,
    Flow,
    Repository,
    Service,
    Api,
    Database,
    Schema,
    Infrastructure,
    Capability,
    ExternalSystem,
    Contract,
    Policy,
    EvidencePack,
    Context,
}

impl DependencyKind {
    /** Report whether a required dependency of this kind must be pinned to a version
     * Input
        - None (uses self)
     * Output
        - bool
    */
    pub(crate) fn needs_pin(self) -> bool {
        matches!(
            self,
            Self::Zone
                | Self::Flow
                | Self::Policy
                | Self::Contract
                | Self::Capability
                | Self::EvidencePack
        )
    }
}

/** A version constraint; the registry never substitutes a different version
 * Variants
    - Exact(String) - exactly this version ("v3", a digest, "2")
    - AtLeast(u32) - an integer version at least this (capabilities)
    - Unpinned - no constraint (not allowed for required pinned kinds)
*/
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "constraint", content = "value", rename_all = "snake_case")]
pub(crate) enum VersionConstraint {
    Exact(String),
    AtLeast(u32),
    Unpinned,
}

impl VersionConstraint {
    /** Check whether a version satisfies the constraint
     * Input
        - version: &str - version found
     * Output
        - bool
    */
    pub(crate) fn admits(&self, version: &str) -> bool {
        match self {
            Self::Exact(wanted) => wanted == version,
            Self::AtLeast(minimum) => version
                .trim_start_matches('v')
                .parse::<u32>()
                .is_ok_and(|found| found >= *minimum),
            Self::Unpinned => true,
        }
    }
}

