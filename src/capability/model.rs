impl CapabilityDefinition {
    /** The digest of the definition's content, the identity of an immutable version
     * Input
        - None (uses self)
     * Output
        - String
    */
    pub(crate) fn digest(&self) -> String {
        digest_json(
            "capability/definition/v1",
            &serde_json::to_value(self).unwrap_or(Value::Null),
        )[..32]
            .to_string()
    }
}

/** Parse a definition from JSON: the schema version is checked first (a newer or older
 * representation is refused, never reinterpreted), then fields, types, and enumerations
 * Input
    - value: &Value - JSON definition
 * Output
    - CapabilityResult<CapabilityDefinition>
    - Error (UnsupportedSchemaVersion or InvalidSchema) naming the problem
*/
pub(crate) fn parse_definition(value: &Value) -> CapabilityResult<CapabilityDefinition> {
    match value.get("schema_version").and_then(Value::as_u64) {
        Some(version) if version == u64::from(CAPABILITY_SCHEMA_VERSION) => {}
        Some(version) => {
            return Err(CapabilityError::new(
                ErrorCode::UnsupportedSchemaVersion,
                format!("capability schema version {version} is not supported (this Crane reads {CAPABILITY_SCHEMA_VERSION})"),
            ))
        }
        None => return Err(CapabilityError::new(ErrorCode::InvalidSchema, "schema_version is missing or not an integer")),
    }
    serde_json::from_value(value.clone())
        .map_err(|error| CapabilityError::new(ErrorCode::InvalidSchema, error.to_string()))
}
